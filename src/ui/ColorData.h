// Snapshot of `GlobalColor.dbc` from build 1.60.1.70707, in the table's
// own row order.
// Vanilla 1.12 has no `GlobalColor.dbc`, so we embed Blizzard's modern
// color table verbatim and expose it via `C_UIColor.GetColors`. The
// addon companion (`!!!ClassicAPI/Util/Color.lua`) loops it the same
// way modern Anniversary's `Blizzard_SharedXMLBase/Color.lua` does:
//
//   for _, dbColor in ipairs(C_UIColor.GetColors()) do
//       _G[dbColor.baseTag]          = CreateColor(dbColor.color:GetRGBA())
//       _G[dbColor.baseTag.."_CODE"] = color:GenerateHexColorMarkup()
//   end
//
// Each `argb` field is the signed `Color` column from the DBC. Decode
// as `uint32_t` and split into 4 bytes:
//   uint32_t v = static_cast<uint32_t>(argb);
//   a = ((v >> 24) & 0xFF) / 255.0
//   r = ((v >> 16) & 0xFF) / 255.0
//   g = ((v >>  8) & 0xFF) / 255.0
//   b = ( v        & 0xFF) / 255.0
//
// Duplicate baseTags in the source DBC (PURE_RED_COLOR, INVASION_*,
// AREA_DESCRIPTION_FONT_COLOR, REFUND_TOOLTIP_COLOR,
// COMPACT_UNIT_FRAME_FRIENDLY_HEALTH_COLOR,
// CHARACTER_FRAME_SIDE_PANEL_SKILL_COLOR) keep only their last row, at
// that row's place — that's the value modern WoW sees after iterating
// `ipairs(DBColors)` to its end.

